import { quoteProvider } from './quote-provider';
import { Provider } from '@angular/core';
import {
  STUDIO_CLIENT,
  StudioClient,
  MockStudioClient,
  ALBUM_SERVICE,
  ANALYSIS_SERVICE,
  AVAILABILITY_SERVICE,
  AUTH_SERVICE,
  CLIENT_GALLERY_SERVICE,
  CONTENT_SERVICE,
  DISCOUNT_SERVICE,
  EQUIPMENT_SERVICE,
  PHOTOGRAPHER_SERVICE,
  PHOTO_SERVICE,
  PRINT_OPTION_SERVICE,
  PRINT_REQUEST_SERVICE,
  PROMOTION_SERVICE,
  PUBLIC_GALLERY_SERVICE,
  QUOTE_SERVICE,
  RATE_SERVICE,
  RETENTION_SERVICE,
  SCHEDULE_SERVICE,
  SESSION_SERVICE,
  STUDIO_SERVICE,
  UPLOAD_SERVICE,
  VENDOR_SERVICE,
} from '@qbs/api';
export function studioProviders(mock = false): Provider[] {
  return [
    { provide: STUDIO_CLIENT, useClass: mock ? MockStudioClient : StudioClient },
    quoteProvider(),
    ...[
      ALBUM_SERVICE,
      ANALYSIS_SERVICE,
      AVAILABILITY_SERVICE,
      AVAILABILITY_SERVICE,
      AUTH_SERVICE,
      CLIENT_GALLERY_SERVICE,
      CONTENT_SERVICE,
      DISCOUNT_SERVICE,
      EQUIPMENT_SERVICE,
      PHOTOGRAPHER_SERVICE,
      PHOTO_SERVICE,
      PRINT_OPTION_SERVICE,
      PRINT_REQUEST_SERVICE,
      PROMOTION_SERVICE,
      PUBLIC_GALLERY_SERVICE,
      RATE_SERVICE,
      RETENTION_SERVICE,
      SCHEDULE_SERVICE,
      RETENTION_SERVICE,
      SCHEDULE_SERVICE,
      SESSION_SERVICE,
      STUDIO_SERVICE,
      UPLOAD_SERVICE,
      VENDOR_SERVICE,
    ].map((token) => ({ provide: token, useExisting: STUDIO_CLIENT })),
  ];
}
